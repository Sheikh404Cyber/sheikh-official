// Generates seed.sql (admin user + starter tools + demos) and ADMIN-TEMP.txt
// (the temporary admin password — written to that file ONLY, never printed).
//
// Usage:  node scripts/seed.mjs
// Then:   wrangler d1 execute sheikh-official-db --file=schema.sql
//         wrangler d1 execute sheikh-official-db --file=seed.sql
// Log in with the ADMIN-TEMP.txt password, then change it from
// Admin → Settings immediately, and delete ADMIN-TEMP.txt + this seed.
//
// Safe to re-run BEFORE first deploy; re-running regenerates the password
// in seed.sql/ADMIN-TEMP.txt (INSERT OR REPLACE keeps them in sync).

import { writeFileSync, chmodSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { hashPassword } from '../functions/lib/auth.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Random readable temp password (24 chars).
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789';
const raw = crypto.getRandomValues(new Uint8Array(24));
const password = [...raw].map((b) => ALPHABET[b % ALPHABET.length]).join('');

const { hash, salt } = await hashPassword(password);

const esc = (s) => String(s).replace(/'/g, "''");

const sql = `-- Sheikh-OFFICIAL seed data — generated by scripts/seed.mjs
-- Apply AFTER schema.sql. The admin password is in ADMIN-TEMP.txt (not here).

INSERT OR REPLACE INTO users (id, name, email, pass_hash, salt, is_admin, can_download, blocked)
VALUES (1, 'Amin Sheikh', 'aminsheikhoffial01@gmail.com', '${esc(hash)}', '${esc(salt)}', 1, 1, 0);

INSERT OR IGNORE INTO tools (id, name, tagline, description, version, size_label, kind, file_path, external_url, sort_order, published) VALUES
  (1, 'SHEIKH QuickVid', 'Script + images → a full video, automatically',
   'Drop in an edit plan and a voice-over and QuickVid builds the whole video for you — automatic timing from the voice, CapCut-style timeline editing, effects, captions and HD export. No manual cutting.',
   '2.0', '95 MB', 'link', '', 'https://github.com/Sheikh404Cyber/sheikh-official/releases', 1, 1),
  (2, 'SHEIKH Flow Auto', 'Auto image generation inside Google Flow',
   'A Chrome extension that reads your storyboard prompt list and generates images one by one in Google Flow — with your character reference attached — then downloads each one with its exact storyboard name, ready for QuickVid.',
   '2.4.1', '204 KB', 'file', '/downloads/SHEIKH-Flow-Auto-V2.4.1.zip', '', 2, 1),
  (3, 'Sheikh Script to Video Editor', 'The first script-to-video editor',
   'The original editor that turns a narration script plus images into a timed video automatically. The tool that started the SHEIKH tools family.',
   '1.1', '32 KB', 'file', '/downloads/sheikh-script-to-video-editor.zip', '', 3, 1);

INSERT OR IGNORE INTO demos (id, name, description, url, image_url, sort_order, published) VALUES
  (1, 'The Wildcut', 'Wildlife & conservation news website built for a client — with its own admin panel',
   'https://thewildcut.pages.dev', '', 1, 1),
  (2, 'RS SHOP', 'Premium watch, sunglass & gift e-commerce store',
   'https://rs-shop.onlinebd.workers.dev/', '', 2, 1);
`;

writeFileSync(join(root, 'seed.sql'), sql, 'utf8');
writeFileSync(
  join(root, 'ADMIN-TEMP.txt'),
  [
    'Sheikh-OFFICIAL — temporary admin login',
    'Email:    aminsheikhoffial01@gmail.com',
    `Password: ${password}`,
    '',
    'Log in at /login, then change this password from Admin → Settings',
    'and DELETE this file. Do not share it.',
    '',
  ].join('\n'),
  'utf8'
);
chmodSync(join(root, 'ADMIN-TEMP.txt'), 0o600);

console.log('Wrote seed.sql and ADMIN-TEMP.txt (password is in ADMIN-TEMP.txt only).');
